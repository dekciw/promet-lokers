// ── Вспомогательные блоки ─────────────────────────────────────────────────

function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    spacing: { before: 400, after: 160 },
    children: [new TextRun({ text, font: FONT, size: 32, bold: true, color: BLUE })],
  });
}

function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    spacing: { before: 280, after: 120 },
    children: [new TextRun({ text, font: FONT, size: 26, bold: true, color: BLUE })],
  });
}

function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    spacing: { before: 220, after: 80 },
    children: [new TextRun({ text, font: FONT, size: 22, bold: true })],
  });
}

function p(runs) {
  if (typeof runs === 'string') runs = [{ text: runs }];
  return new Paragraph({
    spacing: { before: 60, after: 60 },
    children: runs.map(r => new TextRun({ font: FONT, size: 20, ...r })),
  });
}

function bullet(runs) {
  if (typeof runs === 'string') runs = [{ text: runs }];
  return new Paragraph({
    bullet: { level: 0 },
    spacing: { before: 50, after: 50 },
    children: runs.map(r => new TextRun({ font: FONT, size: 20, ...r })),
  });
}

function spacer() {
  return new Paragraph({ spacing: { before: 100, after: 100 }, children: [] });
}

function hr() {
  return new Paragraph({
    spacing: { before: 160, after: 160 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: BLUE } },
    children: [],
  });
}

function boxBlue(runs) {
  if (typeof runs === 'string') runs = [{ text: runs }];
  return new Paragraph({
    spacing: { before: 100, after: 100 },
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: BLUE_LIGHT },
    children: runs.map(r => new TextRun({ font: FONT, size: 20, ...r })),
  });
}

function boxGreen(lines) {
  const children = [];
  lines.forEach((line, i) => {
    if (i > 0) children.push(new TextRun({ text: '\n', font: FONT, size: 20 }));
    if (typeof line === 'string') {
      children.push(new TextRun({ text: line, font: FONT, size: 20 }));
    } else {
      children.push(new TextRun({ font: FONT, size: 20, ...line }));
    }
  });
  return new Paragraph({
    spacing: { before: 100, after: 100 },
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: GREEN_LIGHT },
    children,
  });
}

function boxYellow(text) {
  return new Paragraph({
    spacing: { before: 100, after: 100 },
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: YELLOW },
    children: [
      new TextRun({ text: 'Важно: ', font: FONT, size: 20, bold: true }),
      new TextRun({ text, font: FONT, size: 20 }),
    ],
  });
}

function boxRed(text) {
  return new Paragraph({
    spacing: { before: 100, after: 100 },
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: RED_LIGHT },
    children: [
      new TextRun({ text: '✗  Не считается автоматически: ', font: FONT, size: 20, bold: true }),
      new TextRun({ text, font: FONT, size: 20 }),
    ],
  });
}

// ── Таблица ───────────────────────────────────────────────────────────────

function tc(text, { bold = false, shade = false, center = false, fill, width } = {}) {
  return new TableCell({
    width: width ? { size: width, type: WidthType.PERCENTAGE } : undefined,
    shading: { type: ShadingType.CLEAR, color: 'auto', fill: fill ?? (shade ? GRAY_ROW : WHITE) },
    margins: { top: 70, bottom: 70, left: 100, right: 100 },
    children: [new Paragraph({
      alignment: center ? AlignmentType.CENTER : AlignmentType.LEFT,
      children: [new TextRun({ text: String(text), font: FONT, size: 19, bold })],
    })],
  });
}

function th(text, width) {
  return tc(text, { bold: true, fill: GRAY_HEADER, center: true, width });
}

function tbl(headers, rows, colWidths) {
  return new Table({
    layout: TableLayoutType.FIXED,
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: [
      new TableRow({
        tableHeader: true,
        children: headers.map((h, i) => th(h, colWidths?.[i])),
      }),
      ...rows.map((row, ri) => new TableRow({
        children: row.map((val, ci) => tc(val, {
          shade: ri % 2 === 1,
          width: colWidths?.[ci],
          center: ci > 0,
        })),
      })),
    ],
  });
}

